def print_grid(state):
    for i in range(0, 9, 3):
        print(state[i:i+3])


def dfs(state, goal, visited):
    if state == goal:
        print("Goal Found!")
        return True

    visited.add(state)

    zero = state.index(0)
    row = zero // 3

    # Down, Right, Up, Left
    for move in [3, 1, -3, -1]:
        new_pos = zero + move

        if 0 <= new_pos < 9:
            new_row = new_pos // 3

            if move in [3, -3] or row == new_row:
                new_state = list(state)
                new_state[zero], new_state[new_pos] = (
                    new_state[new_pos], new_state[zero]
                )
                new_state = tuple(new_state)

                if new_state not in visited:
                    print("\nStep:")
                    print_grid(new_state)

                    if dfs(new_state, goal, visited):
                        return True

    return False


