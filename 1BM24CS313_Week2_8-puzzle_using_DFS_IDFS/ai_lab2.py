def print_as_grid(state):
    print("[", state[0], state[1], state[2], "]")
    print("[", state[3], state[4], state[5], "]")
    print("[", state[6], state[7], state[8], "]")
    print("-----------")


def dfs_limited(state, goal, limit, depth, visited, path):

    if state == goal:
        print("\n--- Goal Reached! ---")

        for step, board in enumerate(path):
            print("\nStep", step)
            print_as_grid(board)

        return True

    if depth >= limit:
        return False

    visited.add(state)

    zero = state.index(0)
    zero_row = zero // 3
    moves = [-3, +3, -1, +1]

    for move in moves:
        new_pos = zero + move

        if 0 <= new_pos <= 8:
            new_row = new_pos // 3

            if move in [-1, +1] and zero_row != new_row:
                continue

            new_state_list = list(state)
            new_state_list[zero], new_state_list[new_pos] = (
                new_state_list[new_pos], new_state_list[zero]
            )
            new_state = tuple(new_state_list)

            if new_state not in visited:
                path.append(new_state)

                if dfs_limited(new_state, goal, limit,
                               depth + 1, visited, path):
                    return True

                path.pop()

    visited.remove(state)
    return False


def iterative_deepening_search(initial_state, goal):
    depth_limit = 0

    while depth_limit <= 30:
        print("\nSearching at depth limit:", depth_limit)
        visited = set()
        path = [initial_state]

        if dfs_limited(initial_state, goal, depth_limit,
                       0, visited, path):
            print("\nSolution found successfully at depth:",
                  depth_limit)
            return True

        depth_limit += 1

    print("No solution found within constraints.")
    return False
