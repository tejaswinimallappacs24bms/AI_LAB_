import re

# Check whether a term is a variable
def is_variable(x):
    return isinstance(x, str) and (
        x.startswith("?") or
        (len(x) == 1 and x.islower())
    )


# Parse the expression
def parse_expression(text):
    tokens = re.findall(
        r'\?[A-Za-z_]\w*|[A-Za-z_]\w*|[(),]', text
    )

    if ''.join(tokens) != re.sub(r'\s+', '', text):
        raise ValueError("Invalid expression")

    pos = 0

    def parse_term():
        nonlocal pos

        if pos >= len(tokens):
            raise ValueError("Invalid expression")

        name = tokens[pos]

        if name in ("(", ")", ","):
            raise ValueError("Invalid term")

        pos += 1

        if pos < len(tokens) and tokens[pos] == "(":
            pos += 1
            args = []

            if pos < len(tokens) and tokens[pos] == ")":
                pos += 1
                return (name, tuple(args))

            while True:
                args.append(parse_term())

                if pos >= len(tokens):
                    raise ValueError("Missing closing bracket")

                if tokens[pos] == ")":
                    pos += 1
                    break

                if tokens[pos] != ",":
                    raise ValueError("Expected comma")

                pos += 1

            return (name, tuple(args))

        return name

    result = parse_term()

    if pos != len(tokens):
        raise ValueError("Extra characters")

    return result


# Apply substitution
def apply_substitution(term, subst):
    if is_variable(term):
        if term in subst:
            return apply_substitution(subst[term], subst)
        return term

    if isinstance(term, tuple):
        name, args = term
        return (name, tuple(
            apply_substitution(x, subst) for x in args
        ))

    return term


# Occurs check
def occurs_check(var, term, subst):
    term = apply_substitution(term, subst)

    if var == term:
        return True

    if isinstance(term, tuple):
        return any(
            occurs_check(var, x, subst)
            for x in term[1]
        )

    return False


# Unification algorithm
def unify(t1, t2, subst):

    t1 = apply_substitution(t1, subst)
    t2 = apply_substitution(t2, subst)

    # Step 1: Check identical expressions
    if t1 == t2:
        return subst

    # Step 2: First term is a variable
    if is_variable(t1):
        if occurs_check(t1, t2, subst):
            return None

        subst[t1] = t2
        return subst

    # Step 3: Second term is a variable
    if is_variable(t2):
        if occurs_check(t2, t1, subst):
            return None

        subst[t2] = t1
        return subst

    # Step 4: Check compound expressions
    if isinstance(t1, tuple) and isinstance(t2, tuple):

        # Check predicate names
        if t1[0] != t2[0]:
            return None

        # Check number of arguments
        if len(t1[1]) != len(t2[1]):
            return None

        # Compare arguments one by one
        for a, b in zip(t1[1], t2[1]):
            subst = unify(a, b, subst)

            if subst is None:
                return None

        return subst

    # Step 5: Unification failure
    return None


# Display expression
def display(term):
    if isinstance(term, tuple):
        name, args = term
        return name + "(" + ", ".join(
            display(x) for x in args
        ) + ")"

    return str(term)


# Main program
print("===== UNIFICATION ALGORITHM =====")

try:
    exp1 = input("Enter first expression: ")
    exp2 = input("Enter second expression: ")

    E1 = parse_expression(exp1)
    E2 = parse_expression(exp2)

    print("\nExpression 1:", display(E1))
    print("Expression 2:", display(E2))

    result = unify(E1, E2, {})

    if result is not None:

        print("\nUnification Successful!")
        print("Most General Unifier (MGU):")

        if result:
            for key in result:
                value = apply_substitution(
                    result[key], result
                )
                print(key, "=", display(value))
        else:
            print("No substitution required.")

    else:
        print("\nUnification Failed!")

except ValueError as e:
    print("Invalid Input:", e)

