import heapq

def print_grid(state):
    for i in range(0, 9, 3):
        print(state[i:i + 3])
    print()

def misplaced_tiles(state, goal):
    count = 0
    for i in range(9):
        if state[i] != 0 and state[i] != goal[i]:
            count += 1
    return count

def get_neighbors(state):
    neighbors = []
    zero = state.index(0)
    row, col = divmod(zero, 3)

    moves = [(-1, 0), (1, 0), (0, -1), (0, 1)]

    for dr, dc in moves:
        nr, nc = row + dr, col + dc

        if 0 <= nr < 3 and 0 <= nc < 3:
            new_pos = nr * 3 + nc
            new_state = list(state)
            new_state[zero], new_state[new_pos] = (
                new_state[new_pos], new_state[zero]
            )
            neighbors.append(tuple(new_state))

    return neighbors

def astar(initial, goal):
    pq = []
    h = misplaced_tiles(initial, goal)
    heapq.heappush(pq, (h, 0, initial))

    parent = {initial: None}
    cost = {initial: 0}

    while pq:
        f, g, current = heapq.heappop(pq)

        if g != cost[current]:
            continue

        if current == goal:
            path = []
            while current is not None:
                path.append(current)
                current = parent[current]

            path.reverse()

            print("\nGoal reached!")
            print("Total moves:", len(path) - 1)
            print("Total steps:", len(path))

            for step, state in enumerate(path):
                g_value = step
                h_value = misplaced_tiles(state, goal)
                f_value = g_value + h_value

                print("Step:", step)
                print("g(n) =", g_value)
                print("h(n) =", h_value)
                print("f(n) =", f_value)
                print_grid(state)

            return

        for neighbor in get_neighbors(current):
            new_g = g + 1

            if neighbor not in cost or new_g < cost[neighbor]:
                cost[neighbor] = new_g
                parent[neighbor] = current

                h = misplaced_tiles(neighbor, goal)
                new_f = new_g + h

                heapq.heappush(
                    pq, (new_f, new_g, neighbor)
                )

    print("No solution found.")

