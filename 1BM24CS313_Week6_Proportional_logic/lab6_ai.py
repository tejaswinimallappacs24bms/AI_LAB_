from itertools import product

def implies(a, b):
    return not a or b

print(" P   Q   R  |  Q->P  P->~Q  Q|R  |  KB")
print("------------------------------------------")

models = []

for P, Q, R in product([False, True], repeat=3):

    s1 = implies(Q, P)
    s2 = implies(P, not Q)
    s3 = Q or R

    KB = s1 and s2 and s3

    values = [P, Q, R, s1, s2, s3, KB]

    print(" ".join(
        f"{'T' if v else 'F':^5}" for v in values[:3]
    ) + "|" + " ".join(
        f"{'T' if v else 'F':^7}" for v in values[3:6]
    ) + f"|  {'T' if KB else 'F'}")

    if KB:
        models.append((P, Q, R))

print("\nModels in which KB is TRUE:")
for model in models:
    print(model)

print("\nEntailment Results:")

print("KB entails R:", all(R for P, Q, R in models))

print("KB entails R -> P:",
      all(implies(R, P) for P, Q, R in models))

print("KB entails Q -> R:",
      all(implies(Q, R) for P, Q, R in models))